// Host tests for the portable firmware layer (firmware/lib/ImuStreamProtocol), run with `npm run test:firmware`.
// Generates a C++ header from the shared golden packets (packages/sensor-protocol/fixtures/v1, SYNTHETIC values)
// and from the app's GATT UUIDs, compiles test_imu_protocol.cpp with the host C++ compiler, and runs it. The
// firmware encoder must reproduce every golden byte that the app's TypeScript codec decodes.
// Needs a C++17 compiler (`c++`, or set CXX). CI runs it on Linux; it is not part of `npm run verify`.
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..', '..', '..');
const LIB = join(ROOT, 'firmware', 'lib', 'ImuStreamProtocol', 'src');
const golden = JSON.parse(readFileSync(join(ROOT, 'packages', 'sensor-protocol', 'fixtures', 'v1', 'golden-packets.json'), 'utf8'));
const constants = readFileSync(join(ROOT, 'packages', 'sensor-protocol', 'src', 'constants.ts'), 'utf8');

const uuid = (key) => {
  const m = new RegExp(`\\b${key}: '([0-9a-f-]{36})'`).exec(constants);
  if (!m) throw new Error(`BLE_UUIDS.${key} not found in packages/sensor-protocol/src/constants.ts`);
  return m[1];
};

const cstr = (s) => JSON.stringify(s);
const sampleRows = golden.valid
  .filter((v) => v.type === 'samples')
  .map((v) => {
    const f = v.fields;
    const flags = (f.streamStart ? 1 : 0) | (f.deviceOverflow ? 2 : 0);
    const samples = f.samples
      .map((s) => `{${s.deviceTimeMs}u, {${s.accel.join(', ')}}, {${s.gyro.join(', ')}}}`)
      .join(',\n      ');
    return `  {${cstr(v.name)}, ${flags}, ${f.accelRange}, ${f.gyroRange}, ${f.channel}, ${f.streamId}, ${f.firstSequence}, ${f.samples.length},\n    {${samples}},\n    ${cstr(v.hex)}}`;
  });
const infoRows = golden.valid
  .filter((v) => v.type === 'device_info')
  .map((v) => {
    const f = v.fields;
    const serial = f.deviceSerial.match(/../g).map((b) => `0x${b}`).join(', ');
    return `  {${cstr(v.name)}, {{${serial}}, ${f.channelCount}, ${f.accelRange}, ${f.gyroRange}, ${f.nominalRateHz}, ${f.firmwareVersion.major}, ${f.firmwareVersion.minor}, ${f.status}}, ${cstr(v.hex)}}`;
  });

const header = `// GENERATED by firmware/test/host/run.mjs from packages/sensor-protocol/fixtures/v1/golden-packets.json.
// SYNTHETIC golden values, not real measurements.
#pragma once
#include "ImuStreamProtocol.h"
struct GoldenSamples { const char* name; uint8_t flags, accel_range, gyro_range, channel; uint16_t stream_id, first_sequence; uint8_t count; imu::RawSample samples[31]; const char* hex; };
struct GoldenInfo { const char* name; imu::DeviceInfo info; const char* hex; };
static const GoldenSamples kGoldenSamples[] = {
${sampleRows.join(',\n')}
};
static const GoldenInfo kGoldenInfo[] = {
${infoRows.join(',\n')}
};
static const char* const kAppServiceUuid = ${cstr(uuid('service'))};
static const char* const kAppSamplesUuid = ${cstr(uuid('samples'))};
static const char* const kAppDeviceInfoUuid = ${cstr(uuid('deviceInfo'))};
`;

const work = mkdtempSync(join(tmpdir(), 'imu-fw-host-'));
let status = 1;
try {
  writeFileSync(join(work, 'golden_fixtures.h'), header);
  const cxx = process.env.CXX || 'c++';
  const exe = join(work, process.platform === 'win32' ? 'host_tests.exe' : 'host_tests');
  const build = spawnSync(
    cxx,
    ['-std=c++17', '-Wall', '-Wextra', '-Werror', '-I', LIB, '-I', work, join(HERE, 'test_imu_protocol.cpp'), join(LIB, 'ImuStreamProtocol.cpp'), '-o', exe],
    { stdio: 'inherit' },
  );
  if (build.error) {
    console.error(`firmware host tests: cannot run the C++ compiler '${cxx}' (${build.error.message}); set CXX`);
  } else if (build.status !== 0) {
    console.error('firmware host tests: compilation failed');
  } else {
    status = spawnSync(exe, [], { stdio: 'inherit' }).status ?? 1;
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
process.exit(status);
